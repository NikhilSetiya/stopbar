// Conformance vectors for spec/approval-signature-v1.md. Generated here and
// checked against the PRODUCTION verifiers (verify.go), as any other
// implementation would check them. Includes negative vectors for every
// check in spec §6 and §8.
//
// Regenerate: go test ./internal/approval -run TestApprovalSignatureVectors -update

import (
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"testing"
	"time"
)

var update = flag.Bool("update", false, "rewrite spec/vectors/approval-signature-v1.json")

const vectorsFile = "../../spec/vectors/approval-signature-v1.json"

type vectorKey struct {
	ID        string `json:"id"`
	Tenant    string `json:"tenant"`
	AgentID   string `json:"agent_id,omitempty"`
	SeedHex   string `json:"seed_hex"`
	PublicB64 string `json:"public_b64url"`
	Kid       string `json:"kid"`
}

type escalationVector struct {
	Name   string           `json:"name"`
	Env    SignedEscalation `json:"envelope"`
	Tenant string           `json:"tenant"`
	Want   EscalationWant   `json:"want"`
	Now    int64            `json:"now"`
	Result string           `json:"result"` // "OK" or an error code
}

type breakerResetVector struct {
	Name   string             `json:"name"`
	Env    SignedBreakerReset `json:"envelope"`
	Want   BreakerResetWant   `json:"want"`
	Now    int64              `json:"now"`
	Result string             `json:"result"`
}

// quorumVector exercises Tally directly (spec §9): Keys are the available
// kids, Votes lists which key votes and in what order (as an index into
// Keys, so the same index may repeat — "same key twice"), and RejectAt
// marks positions in Votes (not Keys) that cast a reject instead of an
// approve.
type quorumVector struct {
	Name     string   `json:"name"`
	Keys     []string `json:"keys"`
	Votes    []int    `json:"votes"`
	RejectAt []int    `json:"reject_at"`
	Quorum   int      `json:"quorum"`
	Result   string   `json:"result"` // Pending, Approved or Rejected
}

type vectorFile struct {
	Spec          string               `json:"spec"`
	Note          string               `json:"note"`
	Keys          []vectorKey          `json:"keys"`
	Escalations   []escalationVector   `json:"escalations"`
	BreakerResets []breakerResetVector `json:"breaker_resets"`
	Quorums       []quorumVector       `json:"quorums"`
}

func vecKey(label string) (vectorKey, ed25519.PrivateKey) {
	seed := sha256.Sum256([]byte(label))
	priv := ed25519.NewKeyFromSeed(seed[:])
	pub := priv.Public().(ed25519.PublicKey)
	return vectorKey{SeedHex: fmt.Sprintf("%x", seed), PublicB64: b64.EncodeToString(pub), Kid: Kid(pub)}, priv
}

func keySetOf(t *testing.T, keys []vectorKey) *KeySet {
	t.Helper()
	ks := make([]Key, 0, len(keys))
	for _, vk := range keys {
		pub, err := b64.DecodeString(vk.PublicB64)
		if err != nil {
			t.Fatal(err)
		}
		ks = append(ks, Key{ID: vk.ID, Tenant: vk.Tenant, AgentID: vk.AgentID, Public: ed25519.PublicKey(pub)})
	}
	set, err := NewKeySet(ks)
	if err != nil {
		t.Fatal(err)
	}
	return set
}

func buildVectors(t *testing.T) vectorFile {
	t.Helper()
	alice, alicePriv := vecKey("stopbar approval-signature-v1 test key alice")
	bob, bobPriv := vecKey("stopbar approval-signature-v1 test key bob")
	outsider, outsiderPriv := vecKey("stopbar approval-signature-v1 test key outsider (never configured)")
	alice.ID, alice.Tenant = "alice", "acme"
	bob.ID, bob.Tenant, bob.AgentID = "bob", "acme", "bob-agent"
	outsider.ID, outsider.Tenant = "outsider", "acme" // present in the vector for reference only; NOT added to keys below

	vf := vectorFile{
		Spec: "approval-signature-v1",
		Note: "Generated by internal/approval/vectors_test.go. Each entry is checked with VerifyEscalation or " +
			"VerifyBreakerReset against a KeySet built from 'keys' (not including any key outside that list, " +
			"e.g. 'outsider' below, which exists only to sign UNKNOWN_KEY vectors); 'result' is OK or a VerifyError code.",
		Keys: []vectorKey{alice, bob},
	}

	now := time.Date(2026, 11, 24, 12, 0, 0, 0, time.UTC)
	nowU := now.Unix()
	escID, payloadHash := "esc_01JD0000000000000000000001", "sha256:2c26b46b68ffc68ff99b453c1d30413413422d706483bfa0f98a5e886266e7ae"
	want := EscalationWant{EscalationID: escID, PayloadHash: payloadHash}

	signEsc := func(priv ed25519.PrivateKey, f func(*EscalationObject)) SignedEscalation {
		o := EscalationObject{EscalationID: escID, PayloadHash: payloadHash, Decision: Approve, Expiry: now.Add(30 * time.Minute).Unix()}
		if f != nil {
			f(&o)
		}
		s, err := SignEscalation(priv, o)
		if err != nil {
			t.Fatal(err)
		}
		return s
	}
	addEsc := func(name string, env SignedEscalation, tenant string, w EscalationWant, at int64, result string) {
		vf.Escalations = append(vf.Escalations, escalationVector{Name: name, Env: env, Tenant: tenant, Want: w, Now: at, Result: result})
	}

	good := signEsc(alicePriv, nil)
	addEsc("allow_approve", good, "acme", want, nowU, "OK")
	addEsc("allow_reject", signEsc(bobPriv, func(o *EscalationObject) { o.Decision = Reject }), "acme", want, nowU, "OK")
	addEsc("wrong_payload_hash", signEsc(alicePriv, func(o *EscalationObject) { o.PayloadHash = "sha256:" + fmt.Sprintf("%064x", 1) }), "acme", want, nowU, CodePayloadMismatch)
	addEsc("wrong_escalation_id", signEsc(alicePriv, func(o *EscalationObject) { o.EscalationID = "esc_other" }), "acme", want, nowU, CodeWrongEscalationID)
	addEsc("replayed_on_another_escalation", signEsc(alicePriv, func(o *EscalationObject) { o.EscalationID = "esc_02" }), "acme", want, nowU, CodeWrongEscalationID)
	addEsc("wrong_decision", signEsc(alicePriv, func(o *EscalationObject) { o.Decision = "maybe" }), "acme", want, nowU, CodeBadDecision)
	addEsc("expired", signEsc(alicePriv, func(o *EscalationObject) { o.Expiry = now.Add(-time.Second).Unix() }), "acme", want, nowU, CodeExpired)
	addEsc("expiry_too_far_ahead", signEsc(alicePriv, func(o *EscalationObject) { o.Expiry = now.Add(2 * time.Hour).Unix() }), "acme", want, nowU, CodeExpiryTooFarAhead)
	addEsc("expiry_exactly_at_bound", signEsc(alicePriv, func(o *EscalationObject) { o.Expiry = now.Add(MaxExpiryAhead).Unix() }), "acme", want, nowU, "OK")
	addEsc("unknown_key", signEsc(outsiderPriv, nil), "acme", want, nowU, CodeUnknownKey)
	addEsc("key_of_another_tenant", good, "other-tenant", want, nowU, CodeWrongTenant)
	addEsc("malformed_signature_encoding", func() SignedEscalation { e := good; e.Sig = "not-valid-base64url!!!"; return e }(), "acme", want, nowU, CodeMalformed)
	addEsc("malformed_signature_length", func() SignedEscalation {
		e := good
		e.Sig = b64.EncodeToString([]byte("too-short"))
		return e
	}(), "acme", want, nowU, CodeMalformed)
	addEsc("tampered_payload_hash_under_valid_signature", func() SignedEscalation { e := good; e.PayloadHash = "sha256:tampered"; return e }(), "acme", want, nowU, CodeBadSignature)
	addEsc("self_approval", signEsc(bobPriv, nil), "acme", EscalationWant{EscalationID: escID, PayloadHash: payloadHash, RequesterID: "bob-agent"}, nowU, CodeSelfApproval)
	addEsc("self_reject_allowed", signEsc(bobPriv, func(o *EscalationObject) { o.Decision = Reject }), "acme", EscalationWant{EscalationID: escID, PayloadHash: payloadHash, RequesterID: "bob-agent"}, nowU, "OK")
	addEsc("bound_approver_different_requester_allowed", signEsc(bobPriv, nil), "acme", EscalationWant{EscalationID: escID, PayloadHash: payloadHash, RequesterID: "someone-else"}, nowU, "OK")

	// ---- breaker reset ----
	tripID := "req_01JD0000000000000000000002"
	rwant := BreakerResetWant{Tenant: "acme", TripRequestID: tripID}
	signReset := func(priv ed25519.PrivateKey, f func(*BreakerResetObject)) SignedBreakerReset {
		o := BreakerResetObject{Tenant: "acme", TripRequestID: tripID, Decision: ResetDecision, Expiry: now.Add(30 * time.Minute).Unix()}
		if f != nil {
			f(&o)
		}
		s, err := SignBreakerReset(priv, o)
		if err != nil {
			t.Fatal(err)
		}
		return s
	}
	addReset := func(name string, env SignedBreakerReset, w BreakerResetWant, at int64, result string) {
		vf.BreakerResets = append(vf.BreakerResets, breakerResetVector{Name: name, Env: env, Want: w, Now: at, Result: result})
	}
	goodReset := signReset(alicePriv, nil)
	addReset("allow_reset", goodReset, rwant, nowU, "OK")
	addReset("wrong_tenant_in_object", signReset(alicePriv, func(o *BreakerResetObject) { o.Tenant = "other-tenant" }), rwant, nowU, CodeWrongTenant)
	addReset("wrong_trip_id", signReset(alicePriv, func(o *BreakerResetObject) { o.TripRequestID = "req_other" }), rwant, nowU, CodeWrongTrip)
	addReset("replayed_on_a_later_trip", signReset(alicePriv, func(o *BreakerResetObject) { o.TripRequestID = "req_03" }), rwant, nowU, CodeWrongTrip)
	addReset("wrong_decision", signReset(alicePriv, func(o *BreakerResetObject) { o.Decision = "approve" }), rwant, nowU, CodeBadDecision)
	addReset("expired", signReset(alicePriv, func(o *BreakerResetObject) { o.Expiry = now.Add(-time.Second).Unix() }), rwant, nowU, CodeExpired)
	addReset("expiry_too_far_ahead", signReset(alicePriv, func(o *BreakerResetObject) { o.Expiry = now.Add(2 * time.Hour).Unix() }), rwant, nowU, CodeExpiryTooFarAhead)
	addReset("unknown_key", signReset(outsiderPriv, nil), rwant, nowU, CodeUnknownKey)
	addReset("key_of_another_tenant", goodReset, BreakerResetWant{Tenant: "other-tenant", TripRequestID: tripID}, nowU, CodeWrongTenant)
	addReset("malformed_signature_encoding", func() SignedBreakerReset { e := goodReset; e.Sig = "***invalid***"; return e }(), rwant, nowU, CodeMalformed)
	addReset("tampered_trip_id_under_valid_signature", func() SignedBreakerReset { e := goodReset; e.TripRequestID = "req_tampered"; return e }(), rwant, nowU, CodeBadSignature)

	// ---- quorum (M-of-N) ----
	vf.Quorums = []quorumVector{
		{Name: "below_quorum_pending", Keys: []string{alice.Kid, bob.Kid}, Votes: []int{0}, Quorum: 2, Result: "Pending"},
		{Name: "quorum_met_approved", Keys: []string{alice.Kid, bob.Kid}, Votes: []int{0, 1}, Quorum: 2, Result: "Approved"},
		{Name: "reject_wins_regardless_of_quorum", Keys: []string{alice.Kid, bob.Kid}, Votes: []int{0, 1}, RejectAt: []int{1}, Quorum: 2, Result: "Rejected"},
		{Name: "same_key_twice_no_double_count", Keys: []string{alice.Kid}, Votes: []int{0, 0}, Quorum: 2, Result: "Pending"},
		{Name: "already_resolved_approve_after_reject", Keys: []string{alice.Kid, bob.Kid}, Votes: []int{0, 1}, RejectAt: []int{0}, Quorum: 1, Result: "Rejected"},
	}

	sort.SliceStable(vf.Escalations, func(i, j int) bool { return vf.Escalations[i].Name < vf.Escalations[j].Name })
	sort.SliceStable(vf.BreakerResets, func(i, j int) bool { return vf.BreakerResets[i].Name < vf.BreakerResets[j].Name })
	return vf
}

func TestApprovalSignatureVectors(t *testing.T) {
	vf := buildVectors(t)

	if *update {
		b, err := json.MarshalIndent(vf, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsFile, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", vectorsFile)
		return
	}

	raw, err := os.ReadFile(vectorsFile)
	if err != nil {
		t.Fatalf("read %s (run with -update first): %v", vectorsFile, err)
	}
	var onDisk vectorFile
	if err := json.Unmarshal(raw, &onDisk); err != nil {
		t.Fatal(err)
	}
	keys := keySetOf(t, onDisk.Keys)

	for _, ev := range onDisk.Escalations {
		t.Run("escalation/"+ev.Name, func(t *testing.T) {
			_, err := VerifyEscalation(keys, ev.Tenant, ev.Env, ev.Want, time.Unix(ev.Now, 0))
			checkResult(t, err, ev.Result)
		})
	}
	for _, rv := range onDisk.BreakerResets {
		t.Run("breaker_reset/"+rv.Name, func(t *testing.T) {
			_, err := VerifyBreakerReset(keys, rv.Env, rv.Want, time.Unix(rv.Now, 0))
			checkResult(t, err, rv.Result)
		})
	}
	for _, qv := range onDisk.Quorums {
		t.Run("quorum/"+qv.Name, func(t *testing.T) {
			runQuorumVector(t, qv)
		})
	}
}

func checkResult(t *testing.T, err error, want string) {
	t.Helper()
	if want == "OK" {
		if err != nil {
			t.Fatalf("got %v, want OK", err)
		}
		return
	}
	ve, ok := err.(*VerifyError)
	if !ok {
		t.Fatalf("err = %v (%T), want *VerifyError %s", err, err, want)
	}
	if ve.Code != want {
		t.Fatalf("code = %s, want %s", ve.Code, want)
	}
}

func runQuorumVector(t *testing.T, qv quorumVector) {
	t.Helper()
	rejectAt := map[int]bool{}
	for _, pos := range qv.RejectAt {
		rejectAt[pos] = true
	}
	tally := NewTally(qv.Quorum)
	now := time.Now()
	var res Resolution
	for pos, keyIdx := range qv.Votes {
		decision := Approve
		if rejectAt[pos] {
			decision = Reject
		}
		var err error
		res, err = tally.Add(Vote{Kid: qv.Keys[keyIdx], Decision: decision, Expiry: now.Add(time.Hour)}, now)
		if err != nil && err != ErrDuplicateVote && err != ErrAlreadyResolved {
			t.Fatalf("vote %d: unexpected error %v", pos, err)
		}
	}
	got := map[Outcome]string{Pending: "Pending", Approved: "Approved", Rejected: "Rejected"}[res.Outcome]
	if got != qv.Result {
		t.Fatalf("outcome = %s, want %s", got, qv.Result)
	}
}
